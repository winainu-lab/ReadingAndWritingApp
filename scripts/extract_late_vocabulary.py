"""Extract practice words from แบบเรียนเร็วใหม่ เล่ม ๑ ตอนปลาย (chapters 25-34).

Usage: python -I -X utf8 scripts/extract_late_vocabulary.py <book.pdf> <out.sql>
Collects (a) "X อ่านว่า Y" pairs, (b) word lists under each "แบบฝึกหัด" heading and
(c) the ร/ล, ฟ/คว, ฝ/ขว comparison grids of chapter 34, then writes a Supabase
migration that adds skills B25-B34 with their words and pronunciations.
"""
from __future__ import annotations

import json
import re
import sys

from pypdf import PdfReader

THAI_DIGITS = str.maketrans("๐๑๒๓๔๕๖๗๘๙", "0123456789")
SKILLS = {
    25: "ตัวสะกดอื่น ๆ ที่อ่านเหมือน น ก ด บ สะกด",
    26: "คำที่มีไม้ทัณฑฆาต ไม่ต้องอ่านออกเสียง",
    27: "ตัวสะกดที่ไม่ต้องอ่านออกเสียง (ตัวควบ สระ ิ ุ)",
    28: "ตัวสะกดที่ใช้ทั้งสะกดและออกเสียงด้วย",
    29: "คำเรียงที่อ่านออกเสียงเหมือนอักษรนำ",
    30: "สระ –อ ลดรูป ตัว ร สะกด และ รร",
    31: "สระ –อ ลดรูป ที่มีตัว ร ไม่ใช่ตัวสะกด",
    32: "ไ–ย (ไม้มลายมีตัว ย) และ ฤ ฤๅ",
    33: "เครื่องหมายที่ใช้แทนตัวหนังสือ",
    34: "คำเทียบ ร กับ ล / ฟ กับ คว / ฝ กับ ขว",
}
LEVEL = "ป.3 ตอนปลาย"
NOTE = "แบบฝึกอ่านจากหนังสือแบบเรียนเร็วใหม่ เล่ม ๑ ตอนปลาย (สพฐ.)"
PHRASE_START = (
    "เป็น", "จึง", "ที่", "ให้", "ต้อง", "ไป", "ใน", "ก็", "และ", "แต่", "อย่า", "ควร", "ได้", "จะ", "มี",
    "เมื่อ", "ตก", "ทั้ง", "คือ", "แปลว่า", "เรียกว่า", "บัดนี้", "นอกจากนี้", "ซึ่ง", "ส่วน", "ใช้", "ถึง",
    "พอ", "เห็น", "ผู้ที่", "ต่าง", "ไม่", "เหล่า", "ข้า", "ถือ", "ท่อง", "ตรวจ", "เกิด", "รู้", "เชิญ",
)
STOP_ANY = ("สะกด", "อ่านออกเสียง", "เช่น", "อธิบาย", "ข้อควรจำ", "อ่านว่า", "indd")
STOP_START = ("บทที่", "เรื่อง", "เพลง", "แม่", "คำเทียบ", "เที่ยว")
THAI_ONLY = re.compile(r"^[\u0E01-\u0E2E\u0E30-\u0E39\u0E40-\u0E4E]+$")


def clean(text: str) -> str:
    text = text.replace("\ufffdา", "ำ").replace("\t", "  ")
    text = re.sub(r"([\u0E01-\u0E2E]) (?=[\u0E31\u0E34-\u0E3A\u0E47-\u0E4E])", r"\1", text)
    text = re.sub(r"(?<=[\u0E01-\u0E2E\u0E30-\u0E3A\u0E47-\u0E4E]) า", "า", text)
    return text


def usable(token: str) -> bool:
    return (
        bool(THAI_ONLY.match(token))
        and 2 <= len(token) <= 9
        and token[0] not in "ะาำัิีึืุู็่้๊๋์ๆ"
        and not token.startswith(PHRASE_START)
        and not re.search(r"([ัิ-ฺ็-๎])", token)
    )


def estimate_syllables(word: str) -> int:
    consonants = len(re.findall(r"[ก-ฮ]", word))
    return 1 if consonants <= 2 else 2 if consonants <= 4 else 3


def sql_text(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def build_sql(chapters: dict[int, dict[str, object]]) -> str:
    seen: dict[str, tuple[int, str | None]] = {}
    for chapter, data in sorted(chapters.items()):
        if chapter not in SKILLS:
            continue
        for word, spoken in data["pairs"].items():  # type: ignore[union-attr]
            if word != spoken and word not in seen:
                seen[word] = (chapter, spoken)
        for word in data["words"]:  # type: ignore[union-attr]
            if word not in seen:
                seen[word] = (chapter, None)
    spoken_forms = {spoken for _, spoken in seen.values() if spoken}
    rows = [
        f"  ({sql_text('B%d' % chapter)}, {sql_text(word)}, {sql_text(spoken) if spoken else 'null'}, {estimate_syllables(word)})"
        for word, (chapter, spoken) in seen.items()
        if word not in spoken_forms
    ]
    separator = ",\n"
    skill_rows = separator.join(
        f"  ({sql_text('B%d' % c)}, {sql_text(name)}, {sql_text(LEVEL)}, {sql_text('บทที่ %d' % c)}, {c})" for c, name in SKILLS.items()
    )
    word_rows = separator.join(rows)
    return f"""-- Generated by scripts/extract_late_vocabulary.py from แบบเรียนเร็วใหม่ เล่ม ๑ ตอนปลาย (สพฐ.).
insert into public.skills (code, name, level_code, description, sort_order) values
{skill_rows}
on conflict (code) do update set
  name = excluded.name,
  level_code = excluded.level_code,
  description = excluded.description,
  sort_order = excluded.sort_order;

create temporary table late_book_vocabulary (
  skill_code text not null,
  word text not null,
  pronunciation text,
  syllable_count integer not null
) on commit drop;

insert into late_book_vocabulary (skill_code, word, pronunciation, syllable_count) values
{word_rows};

insert into public.words (display_text, normalized_text, pronunciation, syllable_count, difficulty, source_note)
select word, word, pronunciation, syllable_count, 3, {sql_text(NOTE)}
from late_book_vocabulary source
where not exists (select 1 from public.words existing where existing.normalized_text = source.word);

update public.words word
set pronunciation = source.pronunciation
from late_book_vocabulary source
where word.normalized_text = source.word and word.pronunciation is null and source.pronunciation is not null;

insert into public.word_skills (word_id, skill_id)
select word.id, skill.id
from late_book_vocabulary source
join public.words word on word.normalized_text = source.word
join public.skills skill on skill.code = source.skill_code
on conflict do nothing;
"""


def main(pdf_path: str, out_path: str) -> None:
    reader = PdfReader(pdf_path)
    chapters: dict[int, dict[str, object]] = {}
    current = None
    for page in reader.pages[14:]:
        text = clean(page.extract_text())
        match = re.search(r"บทที่\s*([๐-๙]+)", text[:80])
        if match:
            current = int(match.group(1).translate(THAI_DIGITS))
        if current is None:
            continue
        entry = chapters.setdefault(current, {"pairs": {}, "words": []})
        for word, spoken in re.findall(r"(\S+)\s+อ่านว่า\s+(\S+)", text):
            if THAI_ONLY.match(word) and THAI_ONLY.match(spoken):
                entry["pairs"][word] = spoken  # type: ignore[index]
        lines = text.split("\n")
        collecting = False
        for line in lines:
            if line.strip().startswith("แบบฝึกหัด") or (current == 34 and line.strip().startswith("เปรียบเทียบ")):
                collecting = True
                continue
            if collecting and (any(marker in line for marker in STOP_ANY) or line.strip().startswith(STOP_START)):
                collecting = False
            if collecting:
                for token in re.split(r"\s{2,}|\s", line.strip()):
                    if usable(token):
                        entry["words"].append(token)  # type: ignore[union-attr]
    with open(out_path, "w", encoding="utf-8") as handle:
        handle.write(build_sql(chapters))  # type: ignore[arg-type]


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
